using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace HotPatata.Editor
{
    /// <summary>
    /// Writes the GameObject/HotPatata Level menus from the catalogue (ARCHITECTURE §27.3) into one file, <see cref="FilePath"/>: one item per
    /// code entry (a submenu of its looks when it has several), in the palette's tab, section and order. Priorities step by 20 between
    /// sections, so Unity draws a separator between them. Menu HotPatata/Level/Write Palette Menus; a test fails when the file is stale.
    /// </summary>
    public static class PaletteMenuWriter
    {
        public const string FilePath = "Assets/EditorTools/Palette/LevelMenus.g.cs";
        /// <summary>Between two sections, and between two tabs.</summary>
        public const int SectionStep = 20, TabStep = 100;

        /// <summary>One menu item: its path, priority, entry and look.</summary>
        public readonly struct Item
        {
            public readonly string Path, Entry, Look;
            public readonly int Priority;

            public Item(string path, int priority, string entry, string look)
            {
                Path = path;
                Priority = priority;
                Entry = entry;
                Look = look;
            }
        }

        /// <summary>Every menu item the catalogue asks for, in order.</summary>
        public static List<Item> Items()
        {
            var items = new List<Item>();
            int p = 10;
            var entries = PaletteCatalog.CodeEntries.Where(e => e.InMenu).ToList();
            foreach (var tab in PaletteCatalog.Tabs)
            {
                var inTab = entries.Where(e => e.Tab == tab).ToList();
                if (inTab.Count == 0) continue;
                foreach (var section in PaletteCatalog.Sections(inTab, tab))
                {
                    foreach (var e in inTab.Where(e => e.Section == section))
                    {
                        if (e.Looks.Count == 1) items.Add(new Item(PaletteCatalog.MenuRoot + tab + "/" + e.Label, p++, e.Id, null));
                        else
                            foreach (var look in e.Looks)
                                items.Add(new Item(PaletteCatalog.MenuRoot + tab + "/" + e.Label + "/" + look.Label, p++, e.Id, look.Id));
                    }
                    p += SectionStep;
                }
                p += TabStep;
            }
            return items;
        }

        /// <summary>The file the catalogue writes.</summary>
        public static string Source()
        {
            var s = new StringBuilder();
            s.AppendLine("// <auto-generated>");
            s.AppendLine("// Written by HotPatata/Level/Write Palette Menus from the palette's catalogue (PaletteCatalog, ARCHITECTURE §27.3).");
            s.AppendLine("// Never edit by hand: add a [PaletteItem] and write the menus again.");
            s.AppendLine("// </auto-generated>");
            s.AppendLine("using UnityEditor;");
            s.AppendLine();
            s.AppendLine("namespace HotPatata.Editor");
            s.AppendLine("{");
            s.AppendLine("    static class LevelMenus");
            s.AppendLine("    {");
            var names = new HashSet<string>();
            foreach (var item in Items())
            {
                string name = MethodName(item);
                while (!names.Add(name)) name += "_";
                string look = item.Look == null ? "" : $", \"{item.Look}\"";
                s.AppendLine($"        [MenuItem(\"{item.Path}\", priority = {item.Priority})] static void {name}() => PaletteCatalog.PlaceFromMenu(\"{item.Entry}\"{look});");
            }
            s.AppendLine("    }");
            s.AppendLine("}");
            return s.ToString();
        }

        static string MethodName(Item item)
        {
            var s = new StringBuilder();
            foreach (char ch in item.Entry + (item.Look == null ? "" : "_" + item.Look))
                s.Append(char.IsLetterOrDigit(ch) ? ch : '_');
            return s.ToString();
        }

        /// <summary>True when the file on disk is what the catalogue writes now.</summary>
        public static bool UpToDate() => File.Exists(FilePath) && File.ReadAllText(FilePath).Replace("\r\n", "\n") == Source().Replace("\r\n", "\n");

        [MenuItem("HotPatata/Level/Write Palette Menus", priority = 62)]
        public static void Write()
        {
            if (UpToDate())
            {
                Debug.Log("[Palette] the menus are up to date.");
                return;
            }
            File.WriteAllText(FilePath, Source());
            AssetDatabase.ImportAsset(FilePath);
            Debug.Log($"[Palette] {Items().Count} menu items written to {FilePath}.");
        }
    }
}
